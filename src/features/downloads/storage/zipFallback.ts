/**
 * zipFallback.ts
 * ---------------------------------------------------------------------------
 * Pure JavaScript `.cbz` writer used when the native downloader module is not
 * linked (Expo Go, iOS, a non-rebuilt dev client). Entries are stored
 * uncompressed because page images are already compressed; the archive is
 * assembled in memory, so the native module is preferred for large chapters.
 * ---------------------------------------------------------------------------
 */

import { File } from "expo-file-system";

interface ZipEntryInput {
  path: string;
  name: string;
}

const CRC_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let index = 0; index < 256; index += 1) {
    let value = index;
    for (let bit = 0; bit < 8; bit += 1) {
      value = value & 1 ? 0xedb88320 ^ (value >>> 1) : value >>> 1;
    }
    table[index] = value >>> 0;
  }
  return table;
})();

function crc32(bytes: Uint8Array): number {
  let crc = 0xffffffff;
  for (let index = 0; index < bytes.length; index += 1) {
    crc = CRC_TABLE[(crc ^ bytes[index]) & 0xff] ^ (crc >>> 8);
  }
  return (crc ^ 0xffffffff) >>> 0;
}

/** Writes a stored-entry zip to `destPath` and returns its size/entry count. */
export async function zipArchive(
  entries: ZipEntryInput[],
  destPath: string,
): Promise<{ size: number; entries: number }> {
  const encoder = new TextEncoder();
  const localChunks: Uint8Array[] = [];
  const centralChunks: Uint8Array[] = [];
  let offset = 0;
  let written = 0;

  for (const entry of entries) {
    const source = new File(entry.path);
    if (!source.exists) continue;
    const bytes = await source.bytes();
    const name = encoder.encode(entry.name);
    const crc = crc32(bytes);

    const local = new Uint8Array(30 + name.length);
    const localView = new DataView(local.buffer);
    localView.setUint32(0, 0x04034b50, true);
    localView.setUint16(4, 20, true);
    localView.setUint16(6, 0, true);
    localView.setUint16(8, 0, true);
    localView.setUint16(10, 0, true);
    localView.setUint16(12, 0x21, true);
    localView.setUint32(14, crc, true);
    localView.setUint32(18, bytes.length, true);
    localView.setUint32(22, bytes.length, true);
    localView.setUint16(26, name.length, true);
    localView.setUint16(28, 0, true);
    local.set(name, 30);

    const central = new Uint8Array(46 + name.length);
    const centralView = new DataView(central.buffer);
    centralView.setUint32(0, 0x02014b50, true);
    centralView.setUint16(4, 20, true);
    centralView.setUint16(6, 20, true);
    centralView.setUint16(8, 0, true);
    centralView.setUint16(10, 0, true);
    centralView.setUint16(12, 0, true);
    centralView.setUint16(14, 0x21, true);
    centralView.setUint32(16, crc, true);
    centralView.setUint32(20, bytes.length, true);
    centralView.setUint32(24, bytes.length, true);
    centralView.setUint16(28, name.length, true);
    centralView.setUint16(30, 0, true);
    centralView.setUint16(32, 0, true);
    centralView.setUint16(34, 0, true);
    centralView.setUint16(36, 0, true);
    centralView.setUint32(38, 0, true);
    centralView.setUint32(42, offset, true);
    central.set(name, 46);

    localChunks.push(local, bytes);
    centralChunks.push(central);
    offset += local.length + bytes.length;
    written += 1;
  }

  const centralSize = centralChunks.reduce((total, chunk) => total + chunk.length, 0);
  const eocd = new Uint8Array(22);
  const eocdView = new DataView(eocd.buffer);
  eocdView.setUint32(0, 0x06054b50, true);
  eocdView.setUint16(8, written, true);
  eocdView.setUint16(10, written, true);
  eocdView.setUint32(12, centralSize, true);
  eocdView.setUint32(16, offset, true);

  const total = offset + centralSize + eocd.length;
  const archive = new Uint8Array(total);
  let position = 0;
  for (const chunk of [...localChunks, ...centralChunks, eocd]) {
    archive.set(chunk, position);
    position += chunk.length;
  }

  const destination = new File(destPath);
  destination.write(archive);
  return { size: total, entries: written };
}
