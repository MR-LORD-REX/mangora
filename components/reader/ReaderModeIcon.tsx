export function modeIconId(
  mode: ReaderReadingMode,
  direction: ReaderPagedDirection = "ltr",
): ReaderModeIconId {
  if (mode === "pagedHorizontal") return direction === "rtl" ? "rtl" : "ltr";
  if (mode === "continuousVertical") return "continuous";
  return "webtoon";
}

export default function ReaderModeIcon({
  mode,
  direction,
  id,
  size = 24,
  color = "#ffffff",
}: {
  mode?: ReaderReadingMode;
  direction?: ReaderPagedDirection;
  id?: ReaderModeIconId;
  size?: number;
  color?: string;
}) {
  const iconId = id ?? modeIconId(mode ?? "webtoon", direction);
  return (
    <Svg width={size} height={size} viewBox="0 -960 960 960">
      <Path d={PATHS[iconId]} fill={color} />
    </Svg>
  );
}
